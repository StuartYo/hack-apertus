"""Render eval/RESULTS.md from eval/results.json (the only source of numbers).

Every figure in RESULTS.md and in the technical report tables is read from results.json,
which run_eval.py fills from the official evaluate.py output. `--check` re-renders and fails
if the committed RESULTS.md differs, so the two can never drift apart.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def row(r):
    s = r["score"]["tasks"]
    a, b = s.get("A", {}), s.get("B", {})
    ma, mb = r["mean_per_case"].get("A", {}), r["mean_per_case"].get("B", {})
    return (f"| `{r['tag']}` | {r['system']} | {r['model'].split('/')[-1]}{' (DRY)' if r['dry'] else ''} | "
            f"{a.get('cases', 0)} / {b.get('cases', 0)} | {fmt(a.get('macro_f1'))} | {fmt(a.get('evidence_score'))} | "
            f"{fmt(b.get('macro_f1'))} | {ma.get('input_tokens', 0):,.0f} / {mb.get('input_tokens', 0):,.0f} | "
            f"{ma.get('inference_time_ms', 0) / 1000:,.1f} / {mb.get('inference_time_ms', 0) / 1000:,.1f} | "
            f"{r['usd']:.4f} |")


def render(results):
    lines = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from `eval/results.json`; do not edit by hand.",
        "Scores come from the official `evaluate.py` (hackapertus-starter, commit 5e69577) run on our",
        "predictions. Splits are by vote date and were frozen in `data/split.json` before any model call:",
        "`holdout` = 5 of 20 vote dates never used for development.",
        "",
        "| run | system | model | cases A / B | A macro-F1 | A evidence | B macro-F1 | input tokens per case A / B | seconds per case A / B | USD |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(r) for r in results]
    lines += ["", "Thresholds for a valid submission: task A macro-F1 >= 0.60, task B macro-F1 >= 0.70.",
              "Seconds per case are wall time per case including queueing behind 3 to 6 parallel workers on a",
              "public endpoint, so they are only comparable within one table row set.", ""]
    notes = [f"- `{r['tag']}`: {r['note']}"
             + (f" ({r['truncated_cases']} booklets cut to fit the context)" if r.get("truncated_cases") else "")
             + (f" ({r['retried_after_error']} case(s) retried once after a transient network error)" if r.get("retried_after_error") else "")
             for r in results if r.get("note")]
    if notes:
        lines += ["Notes:", ""] + notes + [""]
    return "\n".join(lines)


def fill(text: str, marker: str, body: str) -> str:
    a, b = f"<!-- {marker}:START -->", f"<!-- {marker}:END -->"
    i, j = text.index(a) + len(a), text.index(b)
    return text[:i] + "\n" + body.strip() + "\n" + text[j:]


def report_parts(results):
    """Held-out runs only, for the technical report; plus a one-sentence headline."""
    hold = [r for r in results if r["split"].startswith("holdout") and not r["dry"]]
    head = ["| run | system | model | cases A / B | A macro-F1 | A evidence | B macro-F1 | input tokens per case A / B | seconds per case A / B | USD |",
            "|---|---|---|---|---|---|---|---|---|---|"] + [row(r) for r in hold]
    table = "\n".join(head) if hold else "_No held-out run recorded yet._"
    headline = ""
    ours = next((r for r in hold if r["system"] == "ours" and r["split"] == "holdout"), None)
    base = next((r for r in hold if r["system"] == "baseline"), None)
    if ours:
        a, b = ours["score"]["tasks"]["A"], ours["score"]["tasks"]["B"]
        headline = (f"On the 5 held-out vote dates ({a['cases']} task A and {b['cases']} task B cases), "
                    f"{ours['model'].split('/')[-1]} with booklet-check reaches macro-F1 {a['macro_f1']:.3f} on task A "
                    f"(evidence score {a['evidence_score']:.3f}) and {b['macro_f1']:.3f} on task B, with "
                    f"{ours['mean_per_case']['A']['input_tokens']:,.0f} input tokens per task A case.")
        if base:
            pair = next((r for r in hold if r["system"] == "ours" and r["split"] == base["split"]), None)
            if pair:
                ba, pa = base["score"]["tasks"]["A"], pair["score"]["tasks"]["A"]
                headline += (f" On the same sample of {ba['cases']} task A cases, the whole-booklet baseline scores "
                             f"{ba['macro_f1']:.3f} (evidence {fmt(ba.get('evidence_score'))}) with "
                             f"{base['mean_per_case']['A']['input_tokens']:,.0f} input tokens per case, "
                             f"against {pa['macro_f1']:.3f} (evidence {fmt(pa.get('evidence_score'))}) with "
                             f"{pair['mean_per_case']['A']['input_tokens']:,.0f} for ours.")
                if base.get("truncated_cases"):
                    headline += (f" In {base['truncated_cases']} of those {ba['cases']} baseline cases the booklet did "
                                 f"not fit the context and was cut at 180,000 characters.")
    return table, headline


def lang_table(results):
    r = next((r for r in results if r["tag"] == "holdout-ours-8b"), None)
    if not r:
        return "_pending_"
    langs = r["score"]["languages"]
    pairs = sorted({k.split(" ", 1)[1] for k in langs})
    lines = ["| pair | " + " | ".join(pairs) + " |", "|---|" + "---|" * len(pairs)]
    for task in ("A", "B"):
        cells = [f"{langs[f'{task} {p}']['macro_f1']:.2f} (n={langs[f'{task} {p}']['cases']})"
                 if f"{task} {p}" in langs else "" for p in pairs]
        lines.append(f"| task {task} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    results = json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))
    text = render(results)
    target = ROOT / "eval" / "RESULTS.md"
    report = ROOT / "technical_report.md"
    table, headline = report_parts(results)
    rep = fill(fill(report.read_text(encoding="utf-8"), "RESULTS", table), "HEADLINE", headline or "_pending_")
    rep = fill(rep, "LANG", lang_table(results))
    if args.check:
        if target.read_text(encoding="utf-8") != text or report.read_text(encoding="utf-8") != rep:
            sys.exit("RESULTS.md or technical_report.md is out of date with eval/results.json")
        print("RESULTS.md and report tables match results.json")
        return
    target.write_text(text, encoding="utf-8")
    report.write_text(rep, encoding="utf-8")
    print(f"wrote {target} and report tables")


if __name__ == "__main__":
    main()
