"""Render eval/RESULTS.md from eval/results.json (the only source of numbers).

Every figure in RESULTS.md and in the technical report tables is read from results.json,
which run_eval.py fills from the official evaluate.py output. `--check` re-renders and fails
if the committed RESULTS.md differs, so the two can never drift apart.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def row(r):
    s = r["score"]["tasks"]
    a, b = s.get("A", {}), s.get("B", {})
    ma, mb = r["mean_per_case"].get("A", {}), r["mean_per_case"].get("B", {})
    return (f"| `{r['tag']}` | {r['system']} | {r['model'].split('/')[-1]}{' (DRY)' if r['dry'] else ''} | "
            f"{a.get('cases', 0)} / {b.get('cases', 0)} | {fmt(a.get('macro_f1'))} | {fmt(a.get('evidence_score'))} | "
            f"{fmt(b.get('macro_f1'))} | {ma.get('input_tokens', 0):,.0f} / {mb.get('input_tokens', 0):,.0f} | "
            f"{ma.get('inference_time_ms', 0) / 1000:,.1f} / {mb.get('inference_time_ms', 0) / 1000:,.1f} | "
            f"{r['usd']:.4f} |")


def render(results):
    lines = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from `eval/results.json`; do not edit by hand.",
        "Scores come from the official `evaluate.py` (hackapertus-starter, commit 5e69577) run on our",
        "predictions. Splits are by vote date and were frozen in `data/split.json` before any model call:",
        "`holdout` = 5 of 20 vote dates never used for development.",
        "",
        "| run | system | model | cases A / B | A macro-F1 | A evidence | B macro-F1 | input tokens per case A / B | seconds per case A / B | USD |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(r) for r in results]
    lines += ["", "Thresholds for a valid submission: task A macro-F1 >= 0.60, task B macro-F1 >= 0.70.",
              "Seconds per case are wall time per case including queueing behind 4 parallel workers on a",
              "public endpoint, so they are only comparable within one table row set.", ""]
    notes = [f"- `{r['tag']}`: {r['note']}" for r in results if r.get("note")]
    if notes:
        lines += ["Notes:", ""] + notes + [""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    results = json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))
    text = render(results)
    target = ROOT / "eval" / "RESULTS.md"
    if args.check:
        if target.read_text(encoding="utf-8") != text:
            sys.exit("eval/RESULTS.md is out of date with eval/results.json")
        print("RESULTS.md matches results.json")
        return
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
