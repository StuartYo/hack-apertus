"""Render eval/RESULTS.md and every number in technical_report.md from the data files.

Sources: eval/results.json (filled by run_eval.py from the official evaluate.py output),
eval/analysis.json (make_analysis.py: numbers that need the gold labels), eval/docker.json
(image size and build time copied from a CI log), eval/spend.jsonl (one line per model call)
and data/split.json. Tables go between <!-- X:START/END --> markers; single numbers in the
prose are written as <!--n:key-->value<!--/n-->.

`--check` re-renders everything and fails if RESULTS.md or the report differs, if a prose
number has no source, or if docs/BookletCheck_Report.pdf was not built from the current
report (source hash in the PDF metadata) or is longer than 6 pages.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "docs" / "BookletCheck_Report.pdf"
MAX_PAGES = 6
FREEZE_COMMIT, FREEZE_TIME = "7b6d3a1", "2026-10-14T23:13:51"
INLINE = re.compile(r"<!--n:(\w+)-->(.*?)<!--/n-->")


def fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def row(r):
    s = r["score"]["tasks"]
    a, b = s.get("A", {}), s.get("B", {})
    ma, mb = r["mean_per_case"].get("A", {}), r["mean_per_case"].get("B", {})
    return (f"| `{r['tag']}` | {r['system']} | {r['model'].split('/')[-1]}{' (DRY)' if r['dry'] else ''} | "
            f"{a.get('cases', 0)} / {b.get('cases', 0)} | {fmt(a.get('macro_f1'))} | {fmt(a.get('evidence_score'))} | "
            f"{fmt(b.get('macro_f1'))} | {ma.get('input_tokens', 0):,.0f} / {mb.get('input_tokens', 0):,.0f} | "
            f"{ma.get('inference_time_ms', 0) / 1000:,.1f} / {mb.get('inference_time_ms', 0) / 1000:,.1f} | "
            f"{r['usd']:.4f} |")


def render(results):
    lines = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from `eval/results.json`; do not edit by hand.",
        "Scores come from the official `evaluate.py` (hackapertus-starter, commit 5e69577) run on our",
        "predictions. The split is by vote date and deterministic (a hash of each date, see `data/split.json`):",
        "`holdout` = 5 of 20 vote dates. No development run used a held-out case, and the first held-out",
        f"model call came after the system was frozen in commit {FREEZE_COMMIT} ({FREEZE_TIME} UTC+8).",
        "",
        "| run | system | model | cases A / B | A macro-F1 | A evidence | B macro-F1 | input tokens per case A / B | seconds per case A / B | USD |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(r) for r in results]
    lines += ["", "Thresholds for a valid submission: task A macro-F1 >= 0.60, task B macro-F1 >= 0.70.",
              "Seconds per case are wall time per case including queueing behind 3 to 6 parallel workers on a",
              "public endpoint, so they are only comparable within one table row set.", ""]
    notes = [f"- `{r['tag']}`: {r['note']}"
             + (f" ({r['truncated_cases']} booklets cut to fit the context)" if r.get("truncated_cases") else "")
             + (f" ({r['retried_after_error']} case(s) retried once after a transient network error)" if r.get("retried_after_error") else "")
             for r in results if r.get("note")]
    if notes:
        lines += ["Notes:", ""] + notes + [""]
    return "\n".join(lines)


def fill(text: str, marker: str, body: str) -> str:
    a, b = f"<!-- {marker}:START -->", f"<!-- {marker}:END -->"
    i, j = text.index(a) + len(a), text.index(b)
    return text[:i] + "\n" + body.strip() + "\n" + text[j:]


def ci(pair, signed=False):
    f = (lambda x: f"{x:+.2f}".replace("-", "−")) if signed else (lambda x: f"{x:.2f}")
    return f"{f(pair[0])} to {f(pair[1])}"


def report_parts(results, an):
    """Held-out runs only, for the technical report; plus the summary paragraph."""
    hold = [r for r in results if r["split"].startswith("holdout") and not r["dry"]]
    head = ["| run | system | model | cases A / B | A macro-F1 | A evidence | B macro-F1 | input tokens per case A / B | seconds per case A / B | USD |",
            "|---|---|---|---|---|---|---|---|---|---|"] + [row(r) for r in hold]
    table = "\n".join(head) if hold else "_No held-out run recorded yet._"
    headline = ""
    ours = next((r for r in hold if r["system"] == "ours" and r["split"] == "holdout"), None)
    base = next((r for r in hold if r["system"] == "baseline"), None)
    if ours:
        a, b = ours["score"]["tasks"]["A"], ours["score"]["tasks"]["B"]
        headline = (f"On the 5 held-out vote dates ({a['cases']} task A and {b['cases']} task B cases), "
                    f"{ours['model'].split('/')[-1]} with booklet-check reaches macro-F1 {a['macro_f1']:.3f} on task A "
                    f"(evidence score {a['evidence_score']:.3f}) and {b['macro_f1']:.3f} on task B, with "
                    f"{ours['mean_per_case']['A']['input_tokens']:,.0f} input tokens per task A case.")
        pair = base and next((r for r in hold if r["system"] == "ours" and r["split"] == base["split"]), None)
        if base and pair:
            ba, pa = base["score"]["tasks"]["A"], pair["score"]["tasks"]["A"]
            bb, pb = base["score"]["tasks"]["B"], pair["score"]["tasks"]["B"]
            h = an["holdout60"]
            nc, cut = h["A"]["not_cut"], h["A"]["cut"]
            headline += (
                f" On the same sample of {ba['cases']} task A cases, the whole-booklet baseline scores "
                f"{ba['macro_f1']:.3f} (evidence {fmt(ba.get('evidence_score'))}) with "
                f"{base['mean_per_case']['A']['input_tokens']:,.0f} input tokens per case, "
                f"against {pa['macro_f1']:.3f} (evidence {fmt(pa.get('evidence_score'))}) with "
                f"{pair['mean_per_case']['A']['input_tokens']:,.0f} for ours. "
                f"For {cut['cases']} of these cases the booklet was cut at 180,000 characters to fit the context, "
                f"but that is not the main reason for the gap: on the {nc['cases']} uncut cases the baseline gets "
                f"{nc['baseline']} of {nc['cases']} labels right and ours {nc['ours']}, on the {cut['cases']} cut ones "
                f"{cut['baseline']} against {cut['ours']}. "
                f"On task B, where the passage is given, the baseline is slightly ahead "
                f"({bb['macro_f1']:.3f} against {pb['macro_f1']:.3f}, {h['B']['correct']['baseline']} against "
                f"{h['B']['correct']['ours']} correct). With 60 cases per task the uncertainty is large: the 95% "
                f"bootstrap interval of our task A advantage is {ci(h['A']['ci95']['ours_minus_baseline'], True)} "
                f"macro-F1.")
    return table, headline


def lang_table(results):
    r = next((r for r in results if r["tag"] == "holdout-ours-8b"), None)
    if not r:
        return "_pending_"
    langs = r["score"]["languages"]
    pairs = sorted({k.split(" ", 1)[1] for k in langs})
    lines = ["| pair | " + " | ".join(pairs) + " |", "|---|" + "---|" * len(pairs)]
    for task in ("A", "B"):
        cells = [f"{langs[f'{task} {p}']['macro_f1']:.2f} (n={langs[f'{task} {p}']['cases']})"
                 if f"{task} {p}" in langs else "" for p in pairs]
        lines.append(f"| task {task} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def jsonl(path):
    return [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]


def facts(results, an, split, spend, docker):
    """Every single number written in the report prose, keyed by its inline marker."""
    by = {r["tag"]: r for r in results}
    f1 = lambda tag, t="A": by[tag]["score"]["tasks"][t]["macro_f1"]  # noqa: E731
    tok = lambda tag: by[tag]["mean_per_case"]["A"]["input_tokens"]  # noqa: E731
    k4, k6, k8 = "devA150b-ours-8b-k4", "devA150b-ours-8b-k6", "devA150b-ours-8b-k8"
    hold_rows = set(split["rows"]["holdout"])
    overlap = 0
    for r in results:
        if not r["split"].startswith("holdout"):
            ids = jsonl(ROOT / "eval" / "runs" / r["tag"] / "predictions.jsonl")
            overlap += sum(int(re.match(r"v1\.1-row-(\d+)-", p["id"]).group(1)) in hold_rows for p in ids)
    calls = [s for s in spend if not s["run"].startswith("external")]
    first = min(s["t"] for s in calls)
    first_hold = min(s["t"] for s in calls if s["run"].startswith("holdout"))
    if first_hold <= FREEZE_TIME:
        sys.exit(f"first held-out call {first_hold} is not after the freeze commit {FREEZE_TIME}")
    h, pa, pb, tk = an["holdout60"], an["holdout_pairs"]["A"], an["holdout_pairs"]["B"], an["dev_topk"]
    ev = lambda p: f"{pa[p]['evidence_found']} of {pa[p]['evidence_cases']}"  # noqa: E731
    others = [p for p in pa if p not in ("de->fr", "de->it")]
    ev_rest = sum(pa[p]["evidence_found"] for p in others) / sum(pa[p]["evidence_cases"] for p in others)
    b_de = [p for p in pb if p.startswith("de->")]
    b_err = sum(v["cases"] - v["correct"] for v in pb.values())
    hold = by["holdout-ours-8b"]
    return {
        "rows_total": f"{len(split['rows']['dev']) + len(split['rows']['holdout']):,}",
        "rows_dev": f"{len(split['rows']['dev']):,}",
        "rows_holdout": f"{len(split['rows']['holdout']):,}",
        "cases_holdout": f"{2 * len(split['rows']['holdout']):,}",
        "first_call": first[11:],
        "freeze_time": FREEZE_TIME[11:],
        "h60_n": str(h["A"]["cases"]),
        "first_holdout_call": first_hold[11:],
        "dev_holdout_overlap": str(overlap),
        "topk_n": str(tk["cases"]),
        "topk_delta": f"{f1(k8) - f1(k4):.3f}",
        "topk_saving": f"{1 - tok(k4) / tok(k8):.0%}",
        "k4_f1": f"{f1(k4):.3f}", "k6_f1": f"{f1(k6):.3f}", "k8_f1": f"{f1(k8):.3f}",
        "k4_correct": str(tk["correct"]["k4"]), "k6_correct": str(tk["correct"]["k6"]),
        "k8_correct": str(tk["correct"]["k8"]),
        "k6_errors": str(by[k6]["routes"].get("error", 0)),
        "topk_ci": ci(tk["ci95_k8_minus_k4"], True),
        "h60_ours_a_ci": ci(h["A"]["ci95"]["ours"]), "h60_base_a_ci": ci(h["A"]["ci95"]["baseline"]),
        "h60_diff_a_ci": ci(h["A"]["ci95"]["ours_minus_baseline"], True),
        "h60_diff_b_ci": ci(h["B"]["ci95"]["ours_minus_baseline"], True),
        "h60_ours_a_correct": str(h["A"]["correct"]["ours"]), "h60_base_a_correct": str(h["A"]["correct"]["baseline"]),
        "h60_ours_b_correct": str(h["B"]["correct"]["ours"]), "h60_base_b_correct": str(h["B"]["correct"]["baseline"]),
        "h60_base_b_f1": f"{f1('holdout60-baseline-8b', 'B'):.3f}", "h60_ours_b_f1": f"{f1('holdout60-ours-8b', 'B'):.3f}",
        "h60_nc_n": str(h["A"]["not_cut"]["cases"]), "h60_nc_base": str(h["A"]["not_cut"]["baseline"]),
        "h60_nc_ours": str(h["A"]["not_cut"]["ours"]), "h60_cut_n": str(h["A"]["cut"]["cases"]),
        "h60_cut_base": str(h["A"]["cut"]["baseline"]), "h60_cut_ours": str(h["A"]["cut"]["ours"]),
        "h60_ours_s": f"{by['holdout60-ours-8b']['mean_per_case']['A']['inference_time_ms'] / 1000:.1f}",
        "h60_base_s": f"{by['holdout60-baseline-8b']['mean_per_case']['A']['inference_time_ms'] / 1000:.1f}",
        "ev_defr": ev("de->fr"), "ev_deit": ev("de->it"), "ev_rest": f"{ev_rest:.2f}",
        "acc_defr": f"{pa['de->fr']['correct']} of {pa['de->fr']['cases']}",
        "acc_deit": f"{pa['de->it']['correct']} of {pa['de->it']['cases']}",
        "b_defr_f1": f"{hold['score']['languages']['B de->fr']['macro_f1']:.2f}",
        "b_deit_f1": f"{hold['score']['languages']['B de->it']['macro_f1']:.2f}",
        "b_de_errors": str(sum(pb[p]["cases"] - pb[p]["correct"] for p in b_de)),
        "b_errors": str(b_err),
        "b_de_cases": str(sum(pb[p]["cases"] for p in b_de)),
        "b_dede": f"{pb['de->de']['correct']} of {pb['de->de']['cases']}",
        "cell_min_n": str(min(v["cases"] for v in pa.values())), "cell_max_n": str(max(v["cases"] for v in pa.values())),
        "cell_step": f"{1 / max(v['cases'] for v in pa.values()):.2f} to {1 / min(v['cases'] for v in pa.values()):.2f}",
        "h60_base_contra_recall": f"{by['holdout60-baseline-8b']['score']['tasks']['A']['per_class']['contradiction']['recall']:.2f}",
        "h60_ours_contra_recall": f"{by['holdout60-ours-8b']['score']['tasks']['A']['per_class']['contradiction']['recall']:.2f}",
        "make_run_s": str(docker["make_run_seconds_two_dry_cases"]),
        "hold_wall_s": f"{hold['wall_s']:.0f}",
        "hold_wall_min": f"{hold['wall_s'] / 60:.0f}",
        "image_mb": f"{docker['image_size_bytes'] / 1e6:,.0f}",
        "build_s": str(docker["build_seconds"]),
        "ci_run": str(docker["ci_run_id"]),
    }


def fill_inline(text, values):
    missing = sorted({k for k, _ in INLINE.findall(text) if k not in values})
    if missing:
        sys.exit(f"report uses numbers with no source: {missing}")
    return INLINE.sub(lambda m: f"<!--n:{m.group(1)}-->{values[m.group(1)]}<!--/n-->", text)


def source_hash() -> str:
    """Hash of everything the PDF is built from (line endings normalised)."""
    h = hashlib.sha256()
    for p in (ROOT / "technical_report.md", ROOT / "docs" / "build_report.py"):
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def pdf_problems():
    from pypdf import PdfReader

    if not PDF.exists():
        return [f"{PDF.name} missing"]
    reader = PdfReader(str(PDF))
    out = []
    if (reader.metadata or {}).get("/SourceSHA256") != source_hash():
        out.append(f"{PDF.name} was not built from the current technical_report.md (run docs/build_report.py)")
    if len(reader.pages) > MAX_PAGES:
        out.append(f"{PDF.name} has {len(reader.pages)} pages, limit {MAX_PAGES}")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    load = lambda name: json.loads((ROOT / name).read_text(encoding="utf-8"))  # noqa: E731
    results, an, split, docker = load("eval/results.json"), load("eval/analysis.json"), load("data/split.json"), \
        load("eval/docker.json")
    spend = jsonl(ROOT / "eval" / "spend.jsonl")
    text = render(results)
    target = ROOT / "eval" / "RESULTS.md"
    report = ROOT / "technical_report.md"
    table, headline = report_parts(results, an)
    rep = fill(fill(report.read_text(encoding="utf-8"), "RESULTS", table), "HEADLINE", headline or "_pending_")
    rep = fill(rep, "LANG", lang_table(results))
    rep = fill_inline(rep, facts(results, an, split, spend, docker))
    if args.check:
        problems = []
        if target.read_text(encoding="utf-8") != text:
            problems.append("RESULTS.md is out of date with eval/results.json")
        if report.read_text(encoding="utf-8") != rep:
            problems.append("technical_report.md is out of date with the data files")
        problems += pdf_problems()
        if problems:
            sys.exit("\n".join(problems))
        print("RESULTS.md, report numbers and report PDF match the data files")
        return
    target.write_text(text, encoding="utf-8", newline="\n")
    report.write_text(rep, encoding="utf-8", newline="\n")
    print(f"wrote {target} and report numbers")


if __name__ == "__main__":
    main()
